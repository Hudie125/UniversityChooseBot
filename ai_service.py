def get_relevant_universities(directions: List[str], country_pref: str) -> List[Dict[str, str]]:
    """Подбирает верифицированные вузы по выбранным направлениям."""
    matched: List[Dict[str, str]] = []
    seen = set()

    for d in directions:
        for cat, unis in VERIFIED_UNIVERSITIES.items():
            if cat.lower() in d.lower() or d.lower() in cat.lower():
                for u in unis:
                    if u["name"] not in seen:
                        matched.append(u)
                        seen.add(u["name"])

    # Если ничего не подобрано (например «Другое»), берем проверенные универсальные топы
    if not matched:
        matched = VERIFIED_UNIVERSITIES["IT и программирование"][:3] + VERIFIED_UNIVERSITIES["Инженерия"][:2]

    return matched[:5]


def get_relevant_specialties(directions: List[str]) -> List[Dict[str, str]]:
    """Подбирает верифицированные направления и программы."""
    matched: List[Dict[str, str]] = []
    seen = set()

    for d in directions:
        for cat, specs in VERIFIED_SPECIALTIES.items():
            if cat.lower() in d.lower() or d.lower() in cat.lower():
                for s in specs:
                    if s["code"] not in seen:
                        matched.append(s)
                        seen.add(s["code"])

    if not matched:
        matched = VERIFIED_SPECIALTIES["IT и программирование"]

    return matched[:4]


