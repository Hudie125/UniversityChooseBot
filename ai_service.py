def clean_markdown_tables(text: str) -> str:
    """
    Удаляет или форматирует остатки Markdown-таблиц, заменяя их на чистые списки.
    """
    lines = text.split("\n")
    cleaned_lines = []
    for line in lines:
        stripped = line.strip()
        # Пропускаем разделительные строки таблиц вида |---|---|
        if stripped.startswith("|") and all(c in "| -:+" for c in stripped):
            continue
        # Преобразуем строки таблицы в аккуратный пункт списка
        if stripped.startswith("|") and stripped.endswith("|"):
            parts = [p.strip() for p in stripped[1:-1].split("|") if p.strip()]
            if parts:
                cleaned_lines.append("• " + " — ".join(parts))
            continue
        cleaned_lines.append(line)
    return "\n".join(cleaned_lines)


